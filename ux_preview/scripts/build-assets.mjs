// Regenerates the two vendored assets of the static UX preview from packages the app already uses.
//   node ux_preview/scripts/build-assets.mjs        (run from the repo root)
// → ux_preview/styles/heroui.css  HeroUI v3 component CSS (Tailwind source compiled to plain CSS)
// → ux_preview/scripts/icons.js   SVG sprite: @gravity-ui/icons + the app's brand icons
import { compile, optimize } from "@tailwindcss/node";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const out = (p) => join(root, "ux_preview", p);

// ── HeroUI ────────────────────────────────────────────────────────────────────
const components = [
  "alert", "alert-dialog", "avatar", "badge", "button", "card", "chip", "close-button", "description",
  "dropdown", "empty-state", "field-error", "input", "input-group", "kbd", "label", "link", "list-box",
  "list-box-item", "menu", "menu-item", "modal", "popover", "progress-bar", "search-field", "select",
  "separator", "skeleton", "spinner", "surface", "switch", "tabs", "textarea", "toast", "toggle-button",
  "toggle-button-group", "tooltip",
];
const herouiVersion = JSON.parse(readFileSync(join(root, "node_modules/@heroui/styles/package.json"), "utf8")).version;
const input = [
  "@layer theme, base, components, utilities;",
  '@import "tailwindcss" source(none);',
  '@import "@heroui/styles/base/base.css" layer(base);',
  '@import "@heroui/styles/base/scrollbar.css" layer(base);',
  ...components.map((c) => `@import "@heroui/styles/components/${c}.css" layer(components);`),
  '@import "@heroui/styles/themes/default" layer(theme);',
  '@import "@heroui/styles/utilities";',
  '@import "@heroui/styles/variants";',
].join("\n");
const compiler = await compile(input, { base: root, onDependency() {} });
const { code } = optimize(compiler.build([]), { minify: true });
writeFileSync(
  out("styles/heroui.css"),
  `/* HeroUI v3 (@heroui/styles ${herouiVersion}): ${components.join(", ")}. Generated by scripts/build-assets.mjs; do not edit. */\n${code}`,
);

// ── Icons ─────────────────────────────────────────────────────────────────────
const gravity = [
  "house", "person", "bookmark", "paper-plane", "comments", "comment", "gear", "arrow-right-from-square",
  "arrow-up-right-from-square", "arrow-left", "arrow-right", "arrow-up", "arrow-down", "arrow-rotate-left",
  "arrows-rotate-right", "arrow-shape-turn-up-right", "check", "circle-check", "circle-check-fill",
  "circle-exclamation", "circle-exclamation-fill", "circle-info", "cloud-arrow-up-in", "copy", "envelope", "eye",
  "eye-slash", "globe", "heart", "link", "pencil", "picture", "plug-connection", "plus", "sparkles", "trash-bin",
  "triangle-exclamation", "xmark", "grip", "ellipsis", "ellipsis-vertical", "chevron-down", "chevron-right",
  "chevron-left", "magnifier", "bars", "lock", "clock", "palette", "video", "chart-column", "bell", "at",
  "qr-code", "smartphone", "thunderbolt", "shield-check", "arrow-up-from-square", "font", "face-smile",
  "circle-xmark", "person-plus", "tray", "circle-play", "logo-facebook", "logo-github", "logo-linkedin",
  "logo-telegram",
];
const symbols = gravity.map((name) => {
  const svg = readFileSync(join(root, "node_modules/@gravity-ui/icons/svgs", `${name}.svg`), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  return `<symbol id="i-${name}" viewBox="${viewBox}">${body}</symbol>`;
});
// Brand marks the app draws itself (components/icons/brand-icons.tsx).
const brands = readFileSync(join(root, "components/icons/brand-icons.tsx"), "utf8");
for (const [, fn, body] of brands.matchAll(/export function Logo(\w+)\([^)]*\)\s*\{[\s\S]*?<svg[^>]*>([\s\S]*?)<\/svg>/g)) {
  const name = `logo-${fn.toLowerCase()}`;
  const markup = body.replace(/\s*\/>/g, "/>").replace(/>\s+</g, "><").trim();
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 16 16" fill="currentColor">${markup}</symbol>`);
}
writeFileSync(
  out("scripts/icons.js"),
  `// Generated by scripts/build-assets.mjs; do not edit. @gravity-ui/icons (MIT) + Linkee brand marks.\n` +
    `document.body.insertAdjacentHTML("afterbegin", ${JSON.stringify(
      `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">${symbols.join("")}</svg>`,
    )});\n`,
);
console.log(`heroui.css ${(code.length / 1024).toFixed(0)} KB · ${symbols.length} icons`);
